#!/usr/bin/env node
// Generates semgrep/idor-route-param.yaml and semgrep/idor-request-id.yaml.
//
// The ownership-guard list is long because Semgrep cannot negate a pattern together with a
// metavariable regex, so every guard shape is spelled out. Edit this file, not the YAML, then run:
//   node packages/discovery/rules/generate-idor-rules.mjs
// and rerun the corpus regression (the stamp covers the generated YAML).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

const header = `# Affidavit's own rules. Written from scratch; no registry rule or rule text is used or copied.
# GENERATED by rules/generate-idor-rules.mjs. Edit the generator, not this file.
#
# IDOR: an identifier the caller controls is read from the request and passed to a data-access
# call, with no ownership check. An ownership check is an if statement that compares the
# identifier with req.session.* or req.user.*, and either
#   - wraps the data-access call (if (id === req.session.userId) { dao.get(id) }), or
#   - comes first and its body returns, throws or calls next(...) when the comparison fails
#     (if (id !== req.session.userId) { return res.sendStatus(403); }).
# A guard whose body does nothing useful does not count. A role check, a query scoped by the
# session id, or a check in middleware or in the data layer is not seen, so these rules over-report
# and the arraignment stage and the Judge decide.
#
# Where the finding goes: when the identifier is first read into a variable, on that statement
# (the source), so it lines up with how the corpus labels IDOR sources; when it is used inline in
# the call, on the call.
#
# Known false positives: a data-access call that is already scoped to the owner some other way
# (for example findOne({ _id: id, owner: req.session.userId })), and an identifier that is checked
# in a helper function or in middleware.
`;

// Receivers that count as data access: names ending in dao, repository, repo, store, model or
// collection (any dotted prefix), capitalised model classes (but not well-known globals such as
// Joi, Math or JSON), prisma, db, knex and sequelize chains, and db.collection(...) or knex(...).
const OBJ_RE =
  '^((?i:[\\w$.]*(dao|repository|repo|store|model|collection))' +
  '|(?!(Joi|Math|JSON|Object|Array|String|Number|Boolean|Promise|Buffer|Date|Symbol|Reflect|Intl|URL|Error|Map|Set)$)[A-Z][A-Za-z0-9_]*' +
  '|(prisma|db|knex|sequelize|this\\.prisma|this\\.db)(\\.[A-Za-z_$][\\w$]*)*' +
  '|(db|this\\.db)\\.collection\\(.*\\)' +
  '|knex\\(.*\\))$';

// Method names that read or change stored data. validate, parse and similar are not on the list,
// so Joi.string().validate(id) and the like are not data access.
const METHOD_RE =
  '^(find|get|update|delete|remove|destroy|save|upsert|create|replace|read|fetch|select|insert|count|lookup|load|list|query|aggregate|distinct|where)\\w*$';

const BODIES = ['return ...;', 'throw ...;', 'next(...);'];

function guards(expr, wrapSink) {
  const out = [];
  for (const auth of ['session', 'user']) {
    const side = `$REQ.${auth}.$S`;
    for (const op of ['===', '==']) {
      for (const cond of [`${expr} ${op} ${side}`, `${side} ${op} ${expr}`]) {
        out.push(wrapSink(cond));
      }
    }
    for (const op of ['!==', '!=']) {
      for (const cond of [`${expr} ${op} ${side}`, `${side} ${op} ${expr}`]) {
        for (const body of BODIES) out.push({ neg: true, text: `if (${cond}) { ... ${body} }` });
      }
    }
  }
  return out;
}

function emitAlt({ finding, prefix, expr, extraRegex, sinkInGuard }) {
  // prefix: statement(s) that bind the identifier, or null when the finding is the call itself.
  const lead = prefix ? `${prefix}\n...\n` : '';
  let s = `          - patterns:
              - pattern: ${finding}
`;
  if (prefix) {
    s += `              - pattern-inside: |
                  ${prefix}
                  ...
                  <... $OBJ.$M(..., <... ${expr} ...>, ...) ...>;
`;
  }
  s += `              - metavariable-regex:
                  metavariable: $OBJ
                  regex: '${OBJ_RE}'
              - metavariable-regex:
                  metavariable: $M
                  regex: '${METHOD_RE}'
`;
  for (const r of extraRegex) {
    s += `              - metavariable-regex:
                  metavariable: ${r.mv}
                  regex: '${r.re}'
`;
  }
  const wrap = (cond) =>
    sinkInGuard
      ? {
          neg: false,
          text: `if (${cond}) { ... <... $O2.$M2(..., <... ${expr} ...>, ...) ...>; ... }`,
        }
      : { neg: false, text: `if (${cond}) {...}` };
  s += `              - pattern-not-inside:
                  pattern-either:
`;
  for (const g of guards(expr, wrap)) {
    // A guard that fails closed protects every later statement in the block, so an inline call
    // (no leading statement to anchor on) needs a trailing ellipsis.
    const body = lead + g.text + (g.neg && !prefix ? '\n...' : '');
    s +=
      `                    - pattern: |\n` +
      body
        .split('\n')
        .map((l) => `                        ${l}`)
        .join('\n') +
      '\n';
  }
  return s;
}

function rule({ id, message, conf, note, alts }) {
  return (
    `rules:
  - id: ${id}
    languages: [javascript, typescript]
    severity: WARNING
    message: >-
${message.map((l) => '      ' + l).join('\n')}
    metadata:
      cls: idor
      cwe: CWE-639
      confidence: ${conf}
      note: ${note}
    patterns:
      - pattern-either:
` + alts.map(emitAlt).join('')
  );
}

const ID_RE = '^(id|\\w*[a-z]Id|\\w*_id)$';

const route = rule({
  id: 'affidavit.idor.route-param-to-data-access',
  message: [
    'A route parameter (req.params) is passed to a data-access call with no ownership check: no',
    'comparison against the signed-in user that wraps the call or returns, throws or calls next',
    "when it fails. Any signed-in caller can change the parameter to read or change another user's",
    'record. Take the owner from the session, or compare before the call.',
  ],
  conf: 'medium',
  note: 'Intra-file only. An ownership check in middleware or in the data layer is not seen.',
  alts: [
    {
      finding: '({ ..., $P, ... } = $REQ.params)',
      prefix: '({ ..., $P, ... } = $REQ.params);',
      expr: '$P',
      extraRegex: [],
      sinkInGuard: true,
    },
    {
      finding: '$P = $REQ.params.$K',
      prefix: '$P = $REQ.params.$K;',
      expr: '$P',
      extraRegex: [],
      sinkInGuard: true,
    },
    {
      finding: '$OBJ.$M(..., <... $REQ.params.$K ...>, ...)',
      prefix: null,
      expr: '$REQ.params.$K',
      extraRegex: [],
      sinkInGuard: false,
    },
  ],
});

const request = rule({
  id: 'affidavit.idor.request-id-to-data-access',
  message: [
    'An identifier field (a name ending in id or Id) from the request body or query string is',
    'passed to a data-access call with no ownership check: no comparison against the signed-in',
    'user that wraps the call or returns, throws or calls next when it fails. Any signed-in caller',
    "can send another user's identifier. Take the owner from the session, or compare before the call.",
  ],
  conf: 'low',
  note: 'Broader than a route parameter. Intra-file only. A role check or a check in middleware is not seen.',
  alts: ['body', 'query'].flatMap((w) => [
    {
      finding: `({ ..., $P, ... } = $REQ.${w})`,
      prefix: `({ ..., $P, ... } = $REQ.${w});`,
      expr: '$P',
      extraRegex: [{ mv: '$P', re: ID_RE }],
      sinkInGuard: true,
    },
    {
      finding: `$P = $REQ.${w}.$K`,
      prefix: `$P = $REQ.${w}.$K;`,
      expr: '$P',
      extraRegex: [{ mv: '$P', re: ID_RE }],
      sinkInGuard: true,
    },
    {
      finding: `$OBJ.$M(..., <... $REQ.${w}.$K ...>, ...)`,
      prefix: null,
      expr: `$REQ.${w}.$K`,
      extraRegex: [{ mv: '$K', re: ID_RE }],
      sinkInGuard: false,
    },
  ]),
});

writeFileSync(join(here, 'semgrep', 'idor-route-param.yaml'), header + route);
writeFileSync(join(here, 'semgrep', 'idor-request-id.yaml'), header + request);
