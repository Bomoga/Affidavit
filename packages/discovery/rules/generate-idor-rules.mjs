#!/usr/bin/env node
// Generates semgrep/idor-route-param.yaml and semgrep/idor-request-id.yaml.
//
// The ownership-guard list is long because Semgrep cannot express "any of these shapes" any other
// way, so every guard shape is spelled out. Edit this file, not the YAML, then run:
//   node packages/discovery/rules/generate-idor-rules.mjs
// and rerun the corpus regression (the stamp covers this file and the generated YAML).
// `node packages/discovery/rules/generate-idor-rules.mjs --check` exits 1 when the committed YAML
// differs from what this file generates (a unit test runs the same check through `build`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

const HEADER = `# Affidavit's own rules. Written from scratch; no registry rule or rule text is used or copied.
# GENERATED by rules/generate-idor-rules.mjs. Edit the generator, not this file.
#
# IDOR: an identifier the caller controls is read from the request and passed to a data-access
# call, with no ownership check on the path to that call. An ownership check is an if statement
# that compares the identifier with an id-like field of the signed-in user (req.session.userId,
# req.user.id, ctx.state.user.id and similar, see AUTH_RE and AUTH_FIELD_RE) and either
#   - wraps the call in its then-branch (an else-branch does not count), or
#   - comes BEFORE the call and its body returns, throws, or calls ctx.throw (a bare next(...)
#     without return does not stop the handler, so it does not count).
# A guard that only logs does not count, and neither does a check placed after the call. Each data
# call is judged on its own: a guarded call does not clear another call on the same identifier.
# A role check, a query scoped by the session id, or a check in middleware or in the data layer is
# not seen, so these rules over-report and the arraignment stage and the Judge decide.
#
# Where the finding goes: when the identifier is first read into a variable, on the request
# expression of that read (req.params, req.body and so on), so it lines up with how the corpus
# labels IDOR sources; when it is used inline in the call, on the call.
#
# Known false positives: a data-access call already scoped to the owner some other way (for example
# findOne({ _id: id, owner: req.session.userId })), and an identifier checked in a helper function
# or in middleware.
#
# Known misses: Next.js app-router handlers that receive { params } as an argument, a params object
# copied under another name (const p = req.params; p.id), identifier names that do not end in id,
# Id, ID or _id (request-id rule only), and guards written some other way (a switch, a ternary, a
# helper such as assertOwner(id)).
`;

// Receivers that count as data access: names ending in dao, repository, repo, store, model or
// collection (any dotted prefix), capitalised model classes (but not well-known globals such as
// Joi, Math or JSON), prisma, db, knex and sequelize chains, and db.collection(...) or knex(...).
const OBJ_RE =
  '^((?i:[\\w$.]*(dao|repository|repo|store|model|collection))' +
  '|(?!(Joi|Math|JSON|Object|Array|String|Number|Boolean|Promise|Buffer|Date|Symbol|Reflect|Intl|URL|Error|Map|Set)$)[A-Z][A-Za-z0-9_]*' +
  '|(prisma|db|knex|sequelize|this\\.prisma|this\\.db)(\\.[A-Za-z_$][\\w$]*)*' +
  '|(db|this\\.db)\\.collection\\(.*\\)' +
  '|knex\\(.*\\))$';

// Method names that read or change stored data. validate, parse and similar are not on the list,
// so Joi.string().validate(id) and the like are not data access.
const METHOD_RE =
  '^(find|get|update|delete|remove|destroy|save|upsert|create|replace|read|fetch|select|insert|count|lookup|load|list|query|aggregate|distinct|where)\\w*$';

// The signed-in user: req.session, req.user, req.auth, req.session.user, ctx.state.user, and an
// id-like field of it. A field such as csrfToken is not an ownership check.
const AUTH_RE = '^([\\w$]+\\.(session|user|auth)(\\.user)?|ctx\\.state\\.user)$';
const AUTH_FIELD_RE = '^(id|_id|userId|user_id|userID|uid|sub)$';

// Identifier names for the request-id rule.
const ID_RE = '^(id|_id|\\w*[a-z](Id|ID)|\\w*_(id|ID))$';
const ID_TAIL = '(id|_id|\\w*[a-z](Id|ID)|\\w*_(id|ID))';

// What a failing guard may do: return, throw, or Koa's ctx.throw. Braced bodies with more than one
// statement and braceless single statements are different shapes in Semgrep.
const BODIES = ['return ...;', 'throw ...;', 'ctx.throw(...);'];

// --- minimal YAML writer (strings, arrays, objects) -------------------------------------------

function yamlLines(value, ind) {
  const pad = ' '.repeat(ind);
  if (Array.isArray(value)) {
    return value.flatMap((item) => {
      const inner = yamlLines(item, ind + 2);
      if (typeof item === 'object' && item !== null) {
        inner[0] = pad + '- ' + inner[0].slice(ind + 2);
        return inner;
      }
      return [pad + '- ' + inner[0].trim(), ...inner.slice(1)];
    });
  }
  if (typeof value === 'object' && value !== null) {
    return Object.entries(value).flatMap(([k, v]) => {
      if (typeof v === 'string') {
        if (v.includes('\n')) {
          return [
            `${pad}${k}: |`,
            ...v
              .replace(/\n$/, '')
              .split('\n')
              .map((l) => `${pad}  ${l}`),
          ];
        }
        // Plain words (ids, severity, class names) stay unquoted so simple tools can read them.
        if (/^[A-Za-z][\w.-]*$/.test(v)) return [`${pad}${k}: ${v}`];
        return [`${pad}${k}: '${v.replace(/'/g, "''")}'`];
      }
      if (typeof v === 'number') return [`${pad}${k}: ${String(v)}`];
      return [`${pad}${k}:`, ...yamlLines(v, ind + 2)];
    });
  }
  return [' '.repeat(ind) + `'${String(value).replace(/'/g, "''")}'`];
}

// --- the rules --------------------------------------------------------------------------------

/** All ownership-guard shapes for one identifier expression, as pattern text built by `wrap`. */
function guardPatterns(expr, wrapNeg, wrapPos) {
  const out = [];
  const sides = ['$AUTH.$S'];
  for (const side of sides) {
    for (const op of ['!==', '!=']) {
      for (const cond of [`${expr} ${op} ${side}`, `${side} ${op} ${expr}`]) {
        for (const body of BODIES) {
          out.push({ pattern: wrapNeg(`if (${cond}) { ... ${body} }`) });
          out.push({ pattern: wrapNeg(`if (${cond}) ${body}`) });
        }
      }
    }
    for (const op of ['===', '==']) {
      for (const cond of [`${expr} ${op} ${side}`, `${side} ${op} ${expr}`]) {
        out.push(...wrapPos(cond));
      }
    }
  }
  return out;
}

function alt({ read, srcRe, expr, extra, inline }) {
  const call = `<... $OBJ.$M(..., <... ${expr} ...>, ...) ...>;`;
  const patterns = [];
  let wrapNeg;
  let wrapPos;
  if (inline) {
    patterns.push({ pattern: `$OBJ.$M(..., <... ${expr} ...>, ...)` });
    // A fail-closed guard earlier in the block protects every later statement.
    wrapNeg = (g) => `${g}\n...`;
    // Only the then-branch counts, so an if with an else does not suppress.
    wrapPos = (cond) => [
      {
        patterns: [
          { pattern: `if (${cond}) {...}` },
          { 'pattern-not': `if (${cond}) {...} else {...}` },
        ],
      },
      {
        patterns: [
          { pattern: `if (${cond}) $STMT;` },
          { 'pattern-not': `if (${cond}) $STMT; else $ELSE;` },
        ],
      },
    ];
  } else {
    patterns.push({ pattern: `${read}\n...\n${call}` }, { 'focus-metavariable': '$SRC' });
    // Order matters: the read, then the guard, then THIS call.
    wrapNeg = (g) => `${read}\n...\n${g}\n...\n${call}`;
    wrapPos = (cond) => [
      {
        patterns: [
          { pattern: `${read}\n...\nif (${cond}) { ... ${call} ... }` },
          { 'pattern-not': `${read}\n...\nif (${cond}) {...} else {...}` },
        ],
      },
      {
        patterns: [
          { pattern: `${read}\n...\nif (${cond}) ${call}` },
          { 'pattern-not': `${read}\n...\nif (${cond}) $STMT; else $ELSE;` },
        ],
      },
    ];
  }
  patterns.push({ 'metavariable-regex': { metavariable: '$SRC', regex: srcRe } });
  for (const r of extra) patterns.push({ 'metavariable-regex': r });
  patterns.push(
    { 'metavariable-regex': { metavariable: '$OBJ', regex: OBJ_RE } },
    { 'metavariable-regex': { metavariable: '$M', regex: METHOD_RE } },
    {
      'pattern-not-inside': {
        patterns: [
          { 'pattern-either': guardPatterns(expr, wrapNeg, wrapPos) },
          { 'metavariable-regex': { metavariable: '$S', regex: AUTH_FIELD_RE } },
          { 'metavariable-regex': { metavariable: '$AUTH', regex: AUTH_RE } },
        ],
      },
    },
  );
  return { patterns };
}

function rule({ id, message, conf, note, alts }) {
  const doc = {
    rules: [
      {
        id,
        languages: ['javascript', 'typescript'],
        severity: 'WARNING',
        message: '@@MESSAGE@@',
        metadata: { cls: 'idor', cwe: 'CWE-639', confidence: conf, note },
        patterns: [{ 'pattern-either': alts.map(alt) }],
      },
    ],
  };
  const text = yamlLines(doc, 0).join('\n') + '\n';
  const folded = '    message: >-\n' + message.map((l) => `      ${l}`).join('\n');
  return text.replace("    message: '@@MESSAGE@@'", folded);
}

const route = (w) => `^[\\w$]+(\\.request)?\\.${w}$`;
const routeField = (w) => `^[\\w$]+(\\.request)?\\.${w}\\.[\\w$]+$`;

export function build() {
  const params = rule({
    id: 'affidavit.idor.route-param-to-data-access',
    message: [
      'A route parameter (req.params) is passed to a data-access call with no ownership check: no',
      'comparison against the signed-in user that wraps the call, or that comes before it and',
      'returns or throws. Any signed-in caller can change the parameter to read or change another',
      "user's record. Take the owner from the session, or compare before the call.",
    ],
    conf: 'medium',
    note: 'Intra-file only. An ownership check in middleware or in the data layer is not seen.',
    alts: [
      { read: '({ ..., $P, ... } = $SRC);', srcRe: route('params'), expr: '$P', extra: [] },
      { read: '$P = $SRC;', srcRe: routeField('params'), expr: '$P', extra: [] },
      { inline: true, srcRe: routeField('params'), expr: '$SRC', extra: [] },
    ],
  });
  const ids = rule({
    id: 'affidavit.idor.request-id-to-data-access',
    message: [
      'An identifier field (a name ending in id, Id or ID) from the request body or query string is',
      'passed to a data-access call with no ownership check: no comparison against the signed-in',
      'user that wraps the call, or that comes before it and returns or throws. Any signed-in',
      "caller can send another user's identifier. Take the owner from the session, or compare",
      'before the call.',
    ],
    conf: 'low',
    note: 'Broader than a route parameter. Intra-file only. A role check or a check in middleware is not seen.',
    alts: [
      {
        read: '({ ..., $P, ... } = $SRC);',
        srcRe: route('(body|query)'),
        expr: '$P',
        extra: [{ metavariable: '$P', regex: ID_RE }],
      },
      {
        read: '$P = $SRC;',
        srcRe: `^[\\w$]+(\\.request)?\\.(body|query)\\.${ID_TAIL}$`,
        expr: '$P',
        extra: [],
      },
      {
        inline: true,
        srcRe: `^[\\w$]+(\\.request)?\\.(body|query)\\.${ID_TAIL}$`,
        expr: '$SRC',
        extra: [],
      },
    ],
  });
  return {
    'semgrep/idor-route-param.yaml': HEADER + params,
    'semgrep/idor-request-id.yaml': HEADER + ids,
  };
}

const norm = (s) => s.replace(/\r\n/g, '\n');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = build();
  if (process.argv.includes('--check')) {
    let bad = false;
    for (const [rel, text] of Object.entries(files)) {
      if (norm(readFileSync(join(here, rel), 'utf8')) !== norm(text)) {
        console.error(`${rel} differs from the generator output`);
        bad = true;
      }
    }
    process.exitCode = bad ? 1 : 0;
  } else {
    for (const [rel, text] of Object.entries(files)) writeFileSync(join(here, rel), text);
  }
}
