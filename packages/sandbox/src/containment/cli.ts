// Runs the containment suite (L2-01) against plain Docker and writes the result table into
// docs/lanes/lane2/containment.md between the generated markers.
//
//   pnpm --filter @affidavit/sandbox containment             report only, exit 0
//   pnpm --filter @affidavit/sandbox containment --require-pass   exit 1 unless every probe passes
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createHostHarness } from './host.js';
import { PlainDockerRunner } from './plain-docker.js';
import { renderMarkdown, runSuite, type SuiteReport } from './suite.js';

const BEGIN =
  '<!-- containment:begin (generated by pnpm --filter @affidavit/sandbox containment) -->';
const END = '<!-- containment:end -->';
const reportPath = join(import.meta.dirname, '../../../../docs/lanes/lane2/containment.md');

/** The Docker bridge gateway: the address a container would use to reach the host. */
function bridgeGateway(): string {
  return execFileSync(
    'docker',
    ['network', 'inspect', 'bridge', '--format', '{{(index .IPAM.Config 0).Gateway}}'],
    { encoding: 'utf8' },
  ).trim();
}

const host = await createHostHarness(bridgeGateway());
let report: SuiteReport;
try {
  report = await runSuite(new PlainDockerRunner(), host);
  const stamp = new Date().toISOString();
  const section = `${BEGIN}\nRun at ${stamp}.\n\n${renderMarkdown(report)}\n${END}`;
  console.log(section);

  const current = await readFile(reportPath, 'utf8');
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < start) throw new Error(`markers not found in ${reportPath}`);
  await writeFile(reportPath, current.slice(0, start) + section + current.slice(end + END.length));
} finally {
  await host.close();
}

if (process.argv.includes('--require-pass') && !report.allPassed) process.exit(1);
