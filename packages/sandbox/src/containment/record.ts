import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createHostHarness } from './host.js';
import { renderMarkdown, runSuite, type SuiteReport } from './suite.js';
import type { HostFixtures, JailRunner } from './types.js';

export const CONTAINMENT_REPORT = join(
  import.meta.dirname,
  '../../../../docs/lanes/lane2/containment.md',
);

/** The Docker bridge gateway: the address a container on the default bridge uses for the host. */
export function bridgeGateway(): string {
  return execFileSync(
    'docker',
    ['network', 'inspect', 'bridge', '--format', '{{(index .IPAM.Config 0).Gateway}}'],
    { encoding: 'utf8' },
  ).trim();
}

/**
 * Runs the suite with the runner `makeRunner` builds, prints the table, and writes it into
 * containment.md between the markers for `kind`. `command` is how to regenerate it.
 */
export async function runAndRecord(
  kind: string,
  command: string,
  makeRunner: (fx: HostFixtures) => JailRunner,
): Promise<SuiteReport> {
  const begin = `<!-- containment:begin runner=${kind} (generated by ${command}) -->`;
  const end = `<!-- containment:end runner=${kind} -->`;
  const host = await createHostHarness(bridgeGateway());
  try {
    const report = await runSuite(makeRunner(host.fixtures()), host);
    const section = `${begin}\nRun at ${new Date().toISOString()}.\n\n${renderMarkdown(report)}\n${end}`;
    console.log(section);
    const current = await readFile(CONTAINMENT_REPORT, 'utf8');
    const start = current.indexOf(begin);
    const stop = current.indexOf(end);
    if (start < 0 || stop < start) {
      throw new Error(`markers for runner=${kind} not found in ${CONTAINMENT_REPORT}`);
    }
    await writeFile(
      CONTAINMENT_REPORT,
      current.slice(0, start) + section + current.slice(stop + end.length),
    );
    return report;
  } finally {
    await host.close();
  }
}
